% Matlab functions for structural thermokinetic modelling
%
% stm_BASEDIR                   - Directory of the toolbox (used for file paths)
%
% Subfolders
%   stm_functions               - Helper functions: options and constraints, saturation values,
%                                epistasis measures, alignment of models, dependency check
%   stm_simple                  - Simple wrapper functions (reference state, model from SBML file)
%   stm_graphics                - Graphics for reference states, response coefficients, and synergies
%   stm_perturbations           - Prediction of perturbation effects and inference of perturbations
%   stm_synergies               - Enzyme synergies: statistics and permutation tests
%   stm_metabolite_fluctuations - Control and noise in metabolic networks
%   stm_mcmc                    - Bayesian (MCMC) posterior sampling based on elasticity sampling
%   stm-utils                   - General utility functions (statistics, graphics)
